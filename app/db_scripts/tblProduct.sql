-- ============================================
-- DROP EXISTING OBJECTS
-- ============================================

DROP TRIGGER IF EXISTS update_tblProduct_pDateUpdated
ON "tblProduct";

DROP FUNCTION IF EXISTS update_pDateUpdated();

DROP POLICY IF EXISTS "User can view all products"
ON "tblProduct";

DROP POLICY IF EXISTS "User can create products"
ON "tblProduct";

DROP POLICY IF EXISTS "User can update assigned or created products"
ON "tblProduct";

DROP POLICY IF EXISTS "User can delete created products"
ON "tblProduct";

DROP INDEX IF EXISTS "idx_tblProduct_ProductID";
DROP INDEX IF EXISTS "idx_tblProduct_pCreatedBy";
DROP INDEX IF EXISTS "idx_tblProduct_pAssignedTo";

DROP TABLE IF EXISTS "tblProduct";




-- Create table
-- Sa PostgreSQL, gumamit ng double quote para ma-preserve
-- ang capitalization ng table at column names.
-- Kapag walang double quote, automatic itong nagiging lowercase.
CREATE TABLE IF NOT EXISTS "tblProduct" (
    --random string unique ID
    --"ProductID" UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    "ProductID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "pImg" TEXT,

    "pName" TEXT,

    "pIngredients" TEXT,
    "pDescription" TEXT,

    "pPrice" DECIMAL(10,2),

    "pCost" DECIMAL(10,2),

    "pCode" TEXT,

    "pIsActive" BOOLEAN DEFAULT FALSE,

    "pAddedBy" TEXT,
    "pCategory" TEXT,

    "pCategoryNotUsed" TEXT
        DEFAULT 'IcedCoffee'
        CHECK ("pCategoryNotUsed" IN ('IcedCoffee', 'NonCoffee', 'Frappe', 'Matcha')),

    "pAssignedTo" UUID
        REFERENCES auth.users(id)
        ON DELETE CASCADE,

    "pCreatedBy" UUID
        REFERENCES auth.users(id)
        ON DELETE CASCADE,

    "pDateAdded" TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

    "pDateUpdated" TIMESTAMP WITH TIME ZONE DEFAULT NOW()

);


-- CREATE INDEX

CREATE INDEX IF NOT EXISTS "idx_tblProduct_ProductID"
ON "tblProduct" ("ProductID");

CREATE INDEX IF NOT EXISTS "idx_tblProduct_pCreatedBy"
ON "tblProduct" ("pCreatedBy");

CREATE INDEX IF NOT EXISTS "idx_tblProduct_pAssignedTo"
ON "tblProduct" ("pAssignedTo");



-- Enable Row Level Security (RLS)

-- Makaka-edit/delete lang ng item
-- kung kanino naka-assign

ALTER TABLE "tblProduct"
ENABLE ROW LEVEL SECURITY;


-- Policy: Users can view all product

CREATE POLICY "User can view all product"

ON "tblProduct"

FOR SELECT

USING (true);


-- Policy: Users can create product

CREATE POLICY "User can create Product"

ON "tblProduct"

FOR INSERT

WITH CHECK (auth.uid() = "pCreatedBy");


-- Policy: User can update Product
-- that they created or assigned

CREATE POLICY "User can update Product that they created or assigned"

ON "tblProduct"

FOR UPDATE

USING (
    auth.uid() = "pCreatedBy"
    OR auth.uid() = "pAssignedTo"
)

WITH CHECK (
    auth.uid() = "pCreatedBy"
    OR auth.uid() = "pAssignedTo"
);


-- Policy: Only creators can delete Product

CREATE POLICY "Only creators can delete Product"

ON "tblProduct"

FOR DELETE

USING (auth.uid() = "pCreatedBy");


-- Function to update timestamp

CREATE OR REPLACE FUNCTION update_pDateUpdated()

RETURNS TRIGGER AS $$

BEGIN

    NEW."pDateUpdated" = NOW();

    RETURN NEW;

END;

$$ LANGUAGE plpgsql;


-- Trigger

CREATE TRIGGER update_tblProduct_pDateUpdated

BEFORE UPDATE ON "tblProduct"

FOR EACH ROW

EXECUTE FUNCTION update_pDateUpdated();